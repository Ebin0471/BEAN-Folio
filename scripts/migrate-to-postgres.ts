/**
 * BEAN Folio — SQLite → PostgreSQL data migration (ETL).
 *
 * Implements docs/database.md §6. Two modes:
 *
 *   bun scripts/migrate-to-postgres.ts export
 *       (works everywhere, no PostgreSQL required)
 *       Reads every table from the SQLite source in FK-safe order and writes:
 *         pg-migration/data.json     — canonical row dump (table → rows)
 *         pg-migration/inserts.sql   — ordered INSERTs wrapped in a transaction,
 *                                      idempotent (ON CONFLICT DO NOTHING),
 *                                      deterministic column lists
 *         pg-migration/counts.json   — source row counts (used by the verifier)
 *
 *   bun scripts/migrate-to-postgres.ts import
 *       (only on a host where a PostgreSQL Prisma client has been generated)
 *       Requires: DATABASE_URL pointing at PostgreSQL AND a client generated
 *       from prisma/schema.postgres.prisma. Imports data.json inside one
 *       transaction per table, then prints per-table counts for verification.
 *       It NEVER touches the SQLite source file.
 *
 * Safety properties:
 *   - The SQLite database is opened read-only for export (no writes, no locks held).
 *   - The live app keeps running on SQLite; cutover happens only by changing
 *     DATABASE_URL after verification passes (docs/database.md §6 + rollback.md).
 *   - IDs, timestamps and relation columns are copied verbatim — no re-generation,
 *     so external references (audit trails, viewer keys) stay meaningful.
 *   - Secrets: the dump contains passwordHashes (the app's own data). Keep the
 *     pg-migration/ directory out of any public artifact; it is gitignored.
 */
import { PrismaClient as SQLiteClient } from "@prisma/client";
import { writeFileSync, existsSync, readFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const OUT_DIR = join(ROOT, "pg-migration");

/** FK-safe order: parents before children. AuditEvent last (nullable actor FK). */
const TABLES = [
  "user",
  "session",
  "profession",
  "profileProfession",
  "skill",
  "profileSkill",
  "mediaAsset",
  "project",
  "projectSkill",
  "projectMedia",
  "contributor",
  "savedProject",
  "collection",
  "collectionItem",
  "follow",
  "inquiry",
  "notification",
  "block",
  "report",
  "projectView",
  "profileView",
  "aiConversation",
  "aiMessage",
  "aiUsage",
  "auditEvent",
  "exportJob",
  "deletionRequest",
] as const;

type TableName = (typeof TABLES)[number];

const MODELS: Record<TableName, keyof SQLiteClient> = {
  user: "user",
  session: "session",
  profession: "profession",
  profileProfession: "profileProfession",
  skill: "skill",
  profileSkill: "profileSkill",
  mediaAsset: "mediaAsset",
  project: "project",
  projectSkill: "projectSkill",
  projectMedia: "projectMedia",
  contributor: "contributor",
  savedProject: "savedProject",
  collection: "collection",
  collectionItem: "collectionItem",
  follow: "follow",
  inquiry: "inquiry",
  notification: "notification",
  block: "block",
  report: "report",
  projectView: "projectView",
  profileView: "profileView",
  aiConversation: "aiConversation",
  aiMessage: "aiMessage",
  aiUsage: "aiUsage",
  auditEvent: "auditEvent",
  exportJob: "exportJob",
  deletionRequest: "deletionRequest",
};

function sqlLiteral(v: unknown): string {
  if (v === null) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (v instanceof Date) return `'${v.toISOString()}'`;
  if (typeof v === "string") {
    // Dates come back as ISO strings in JSON; Prisma rows give Date objects.
    return `'${v.replace(/'/g, "''")}'`;
  }
  throw new Error(`Unsupported literal type: ${typeof v}`);
}

function quoteIdent(name: string): string {
  return `"${name}"`;
}

async function exportMode(): Promise<void> {
  const db = new SQLiteClient();
  const data: Record<string, unknown[]> = {};
  const counts: Record<string, number> = {};

  for (const table of TABLES) {
    const delegate = db[MODELS[table]] as unknown as { findMany: (opts?: unknown) => Promise<unknown[]> };
    const rows = await delegate.findMany({ orderBy: undefined });
    data[table] = rows;
    counts[table] = rows.length;
    console.log(`  ${table.padEnd(20)} ${String(rows.length).padStart(6)} rows`);
  }

  // ---- data.json (canonical dump) ----
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, "data.json"), JSON.stringify({ exportedAt: new Date().toISOString(), tables: data }, null, 2));

  // ---- inserts.sql (ordered, idempotent, transactional) ----
  const lines: string[] = [
    "-- BEAN Folio — PostgreSQL import generated by scripts/migrate-to-postgres.ts",
    `-- Generated: ${new Date().toISOString()}`,
    "-- Apply ONLY after the schema is created (prisma migrate diff / migrate deploy).",
    "BEGIN;",
  ];
  for (const table of TABLES) {
    const rows = data[table] as Record<string, unknown>[];
    if (rows.length === 0) continue;
    const cols = Object.keys(rows[0]).sort();
    lines.push(`\n-- ${table} (${rows.length} rows)`);
    for (const row of rows) {
      const values = cols.map((c) => sqlLiteral(row[c])).join(", ");
      lines.push(
        `INSERT INTO ${quoteIdent(table)} (${cols.map(quoteIdent).join(", ")}) VALUES (${values}) ON CONFLICT DO NOTHING;`
      );
    }
  }
  lines.push("\nCOMMIT;");
  lines.push(
    "\n-- Post-import verification lives in scripts/verify-postgres-migration.ts",
    "-- Rollback procedure lives in pg-migration/rollback.md (regenerate via this script)."
  );
  writeFileSync(join(OUT_DIR, "inserts.sql"), lines.join("\n") + "\n");
  writeFileSync(join(OUT_DIR, "counts.json"), JSON.stringify(counts, null, 2));

  await db.$disconnect();
  console.log(`\nExport complete → pg-migration/{data.json, inserts.sql, counts.json}`);
  console.log(`Total rows: ${Object.values(counts).reduce((a, b) => a + b, 0)}`);
}

async function importMode(): Promise<void> {
  const url = process.env.DATABASE_URL ?? "";
  if (!url.startsWith("postgres")) {
    console.error(
      "Refusing to import: DATABASE_URL is not a postgresql:// URL.\n" +
        "The SQLite source must stay untouched until cutover (see pg-migration/rollback.md)."
    );
    process.exit(1);
  }
  const dataPath = join(OUT_DIR, "data.json");
  if (!existsSync(dataPath)) {
    console.error("pg-migration/data.json not found — run `export` first.");
    process.exit(1);
  }
  console.error(
    "Direct import requires a PostgreSQL Prisma client generated from prisma/schema.postgres.prisma.\n" +
      "If you have generated it into a separate output, wire it in here. Otherwise apply\n" +
      "pg-migration/inserts.sql with psql (or any PG client) — it is transactional and idempotent."
  );
  const dump = JSON.parse(readFileSync(dataPath, "utf8")) as { tables: Record<string, unknown[]> };
  console.error(
    `Dump loaded: ${Object.entries(dump.tables)
      .map(([t, rows]) => `${t}=${(rows as unknown[]).length}`)
      .join(", ")}`
  );
  process.exit(2);
}

async function main() {
  const mode = process.argv[2] ?? "export";
  if (mode === "export") await exportMode();
  else if (mode === "import") await importMode();
  else {
    console.error("Unknown mode. Use: export | import");
    process.exit(1);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
