export interface CreativePipelineOutput {
  image: { bytes: Buffer; mime: string; width: number; height: number };
  provider: string;
  model: string;
  warnings: string[];
  attempts: number;
  qualitySummary: string;
}

/** Injectable pipeline — production runs the REAL LAXII banner pipeline. */
export type CreativePipeline = (brief: DesignBrief, ctx: { userId: string }) => Promise<CreativePipelineOutput>;

export function defaultCreativePipeline(): CreativePipeline {
  return async (brief, { userId }) => {
    const { runBannerPipeline } = await import("@/lib/laxii/banner-pipeline");
    const result = await runBannerPipeline(brief, [], { promptBase: compileBriefPrompt(brief) }, { userId });
    const passed = result.quality.findings.filter((f) => f.status === "pass").length;
    const failed = result.quality.findings.filter((f) => f.status === "fail").length;
    return {
      image: result.image,
      provider: result.provider,
      model: result.model,
      warnings: result.warnings,
      attempts: result.attempts.length,
      qualitySummary: `overall ${result.quality.overall}; ${passed} checks passed, ${failed} failed (${result.quality.evaluator})`,
    };
  };
}

export async function approveCreativeAssetTask(input: { userId: string; taskId: string; pipeline?: CreativePipeline }): Promise<void> {
  const row = await loadCreativeTask(input.userId, input.taskId);
  if (row.status !== "AWAITING_APPROVAL") {
    throw new CreativeTaskError(`Task is ${row.status}; only AWAITING_APPROVAL tasks can be approved`, 409, row.id);
  }
  const payload = payloadOf(row);
  if (!payload?.brief) throw new CreativeTaskError("Task has no validated creative brief", 409, row.id);

  const steps = upsertStep(parseSteps(row.stepsJson), "generate", "running");
  await db.agentTask.update({ where: { id: row.id }, data: { status: "GENERATING", stepsJson: JSON.stringify(steps) } });

  try {
    const pipeline = input.pipeline ?? defaultCreativePipeline();
    const out = await pipeline(payload.brief, { userId: input.userId });

    // LAXII retains responsibility for generation quality — verify the
    // delivered pixels honestly before registering the artifact.
    if (out.image.width !== payload.brief.canvas.width || out.image.height !== payload.brief.canvas.height) {
      throw new CreativeTaskError(
        `Generated asset is ${out.image.width}×${out.image.height}; expected ${payload.brief.canvas.width}×${payload.brief.canvas.height}`,
        500,
        row.id
      );
    }
    if (out.image.bytes.byteLength > MAX_ARTIFACT_BYTES) {
      throw new CreativeTaskError("Generated asset exceeds the artifact size cap", 500, row.id);
    }

    const mediaId = await storeGeneratedMedia(
      input.userId,
      out.image.bytes,
      out.image.mime,
      out.image.width,
      out.image.height,
      `GIFTZ creative asset ${new Date().toISOString().slice(0, 10)}.png`
    );
    const artifact = await registerArtifact({
      userId: input.userId,
      mediaId,
      sourceTaskId: row.id,
      role: "BANNER",
    });

    payload.artifactId = artifact.id;
    payload.mediaId = mediaId;
    payload.result = {
      width: out.image.width,
      height: out.image.height,
      mime: out.image.mime,
      sizeBytes: out.image.bytes.byteLength,
      provider: out.provider,
      model: out.model,
      attempts: out.attempts,
      qualitySummary: out.qualitySummary,
    };
    const doneSteps = upsertStep(steps, "generate", "done", `${out.image.width}×${out.image.height} registered`);
    await db.agentTask.update({
      where: { id: row.id },
      data: { status: "COMPLETED", stepsJson: JSON.stringify(doneSteps), resultJson: JSON.stringify(payload), error: null },
    });
    void recordAiUsage(input.userId, "giftz-creative-generate");
  } catch (error) {
    const failSteps = upsertStep(steps, "generate", "failed", error instanceof ArtifactError || error instanceof CreativeTaskError ? error.message : "generation failed");
    await db.agentTask
      .update({
        where: { id: row.id },
        data: {
          status: "FAILED",
          stepsJson: JSON.stringify(failSteps),
          error: (error instanceof Error ? error.message : "generation failed").slice(0, 300),
        },
      })
      .catch(() => undefined);
    if (error instanceof CreativeTaskError) throw error;
    throw new CreativeTaskError(error instanceof Error ? error.message : "generation failed", 500, row.id);
  }
}

export async function rejectCreativeAssetTask(userId: string, taskId: string, reason?: string): Promise<void> {
  const row = await loadCreativeTask(userId, taskId);
  if (row.status !== "AWAITING_APPROVAL") {
    throw new CreativeTaskError(`Task is ${row.status}; only AWAITING_APPROVAL tasks can be rejected`, 409, row.id);
  }
  const steps = upsertStep(parseSteps(row.stepsJson), "approve", "failed", "rejected by the user");
  await db.agentTask.update({
    where: { id: row.id },
    data: { status: "CANCELLED", stepsJson: JSON.stringify(steps), error: reason?.slice(0, 300) ?? "Rejected by the user" },
  });
}

// ---------------------------------------------------------------------------
// Integration: separate approval → ENGINEERING_TASK with the linked artifact
// ---------------------------------------------------------------------------

export async function createCreativeIntegrationTask(input: { userId: string; taskId: string; request: string; provider?: import("./types").GiftzStepProvider }): Promise<{ integrationTaskId: string }> {
  const request = input.request?.trim();
  if (!request || request.length < 8 || request.length > 2000) {
    throw new CreativeTaskError("Describe the integration in 8–2000 characters");
  }
  const row = await loadCreativeTask(input.userId, input.taskId);
  if (row.status !== "COMPLETED") {
    throw new CreativeTaskError(`Task is ${row.status}; only COMPLETED creative tasks can be integrated`, 409, row.id);
  }
  const payload = payloadOf(row);
  if (!payload?.artifactId || !payload.mediaId) {
    throw new CreativeTaskError("Task has no generated asset to integrate", 409, row.id);
  }
  if (payload.integrationTaskId) {
    // Idempotent retry: re-attach to the existing integration task.
    const existing = await db.agentTask.findUnique({ where: { id: payload.integrationTaskId }, select: { id: true, status: true } });
    if (existing) return { integrationTaskId: existing.id };
  }
  const artifact = await resolveArtifact(input.userId, payload.artifactId);
  if (artifact.status === "CONSUMED" && artifact.destinationTaskId) {
    throw new CreativeTaskError("This asset has already been integrated", 409, payload.artifactId);
  }
  if (!row.repoId) throw new CreativeTaskError("Task has no repository", 409, row.id);

  const engineeringRequest = [
    `Integrate the approved LAXII banner asset (${payload.result?.width ?? "?"}×${payload.result?.height ?? "?"} ${payload.result?.mime ?? "image/png"}) into this repository.`,
    `Write the asset's exact bytes to "${ASSET_TARGET_PATH}" (the system provides the binary content — declare it as a create_file step and do not invent file content) and modify the relevant existing source/test files so the asset is actually referenced and covered by tests.`,
    `Integration requirements from the user: ${request}`,
  ].join(" ");

  const out = await createEngineeringTask({
    userId: input.userId,
    repoId: row.repoId,
    request: engineeringRequest,
    parentTaskId: row.id,
    linkedArtifact: { artifactId: payload.artifactId, assetTargets: [ASSET_TARGET_PATH] },
    ...(input.provider ? { provider: input.provider } : {}),
  });

  // Single-shot consumption — a duplicate integration is refused honestly.
  await consumeArtifact(input.userId, payload.artifactId, out.taskId);

  payload.integrationTaskId = out.taskId;
  const steps = upsertStep(parseSteps(row.stepsJson), "integrate", "done", `engineering task ${out.taskId}`);
  await db.agentTask.update({
    where: { id: row.id },
    data: { resultJson: JSON.stringify(payload), stepsJson: JSON.stringify(steps) },
  });
  return { integrationTaskId: out.taskId };
}

