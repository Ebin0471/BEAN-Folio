const ACTIVE_STATUSES = ["QUEUED", "ANALYZING", "PROPOSING", "AWAITING_APPROVAL", "GENERATING"];

export class CreativeTaskError extends Error {
  readonly status: number;
  readonly taskId?: string;
  constructor(message: string, status = 400, taskId?: string) {
    super(message);
    this.name = "CreativeTaskError";
    this.status = status;
    this.taskId = taskId;
  }
}

