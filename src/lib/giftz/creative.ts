/**
 * Phase 5 — Workflow 1: CODE GIFTZ → LAXII creative asset requests.
 *
 * An engineering context needs a creative asset (e.g. a portfolio banner for
 * the site being built). CODE GIFTZ inspects the authorized repository,
 * proposes a structured creative request, the USER APPROVES the handoff, and
 * only then does LAXII generate through its EXISTING pipeline (structured
 * brief → generate → deterministic typography → measured quality evaluation →
 * bounded refinement → exact 2048×687 export). LAXII keeps full responsibility
 * for image generation + quality evaluation; CODE GIFTZ keeps responsibility
 * for repository changes — integrating the asset into the workspace is a
 * SEPARATE approval and runs through the engineering task pipeline.
 *
 * Hard rules: creative generation NEVER modifies the repository; the asset is
 * registered as a shared artifact (ownership/mime/size/dims verified) and
 * consumed exactly once by the integration task.
 */

