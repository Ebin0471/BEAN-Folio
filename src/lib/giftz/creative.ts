export const creativeProposalSchema = z.object({
  headline: z.string().trim().min(1).max(40),
  visualDirection: z.string().trim().min(8).max(600),
  audience: z.string().trim().max(200).optional(),
  avoid: z.array(z.string().trim().min(1).max(120)).max(6).default([]),
  rationale: z.string().trim().max(400),
});
export type CreativeProposal = z.infer<typeof creativeProposalSchema>;

const PROPOSAL_SYSTEM = [
  "You are GIFTZ, the engineering agent of BEAN Folio.",
  "You prepare structured creative-asset requests for LAXII, the creative engine.",
  "You never invent capabilities, never request secret content, and reply with ONLY the JSON object.",
].join(" ");

const PROPOSAL_SCHEMA_DOC = `{
  "headline": string (1..40 chars — the exact banner headline text, quoted style),
  "visualDirection": string (8..600 — scene, mood, lighting, palette intent),
  "audience": string optional (<=200 — who this asset is for),
  "avoid": [string] (0..6 — what the scene must NOT contain),
  "rationale": string (<=400 — why this asset serves the engineering request)
}`;

function proposalUserPrompt(request: string, digest: InspectionDigest): string {
  return [
    "Engineering request (verbatim):",
    request,
    "",
    "Repository inventory (metadata only — read-only inspection):",
    `Files: ${digest.fileCount} · package: ${digest.packageName ?? "none"} · frameworks: ${digest.frameworks.join(", ") || "none detected"}`,
    `Tree: ${digest.tree.slice(0, 24).map((t) => t.path).join(" · ")}`,
    "",
    "The asset will be a 2048×687 portfolio banner generated by LAXII (text is rendered deterministically by LAXII — the scene must stay free of lettering).",
    "Return the creative request in exactly this JSON schema:",
    PROPOSAL_SCHEMA_DOC,
  ].join("\n");
}

/** Injectable proposal provider — tests script it; production uses the gateway. */
export interface CreativeProposalProvider {
  propose(input: { request: string; digest: InspectionDigest; repairIssues?: string[]; previousProposal?: unknown }): Promise<string> | string;
}

export function createGatewayCreativeProvider(userId: string): CreativeProposalProvider {
  return {
    async propose({ request, digest, repairIssues, previousProposal }) {
      const user = repairIssues?.length
        ? [
            "Your previous proposal was rejected by the validator. Fix EXACTLY these issues and return the corrected JSON:",
            ...repairIssues.map((i) => `- ${i}`),
            "",
            "Previous proposal (invalid):",
            JSON.stringify(previousProposal ?? {}).slice(0, 4000),
            "",
            proposalUserPrompt(request, digest),
          ].join("\n")
        : proposalUserPrompt(request, digest);
      const { text } = await aiComplete(PROPOSAL_SYSTEM, [{ role: "user", content: user }], {
        temperature: 0.3,
        thinking: true,
        timeoutMs: AI_DEEP_TIMEOUT_MS,
        agent: "CODE_GIFTZ",
        feature: "giftz-creative-brief",
        userId,
      });
      return text;
    },
  };
}

function stripFences(text: string): string {
  const fence = /```(?:json)?\s*([\s\S]*?)```/.exec(text);
  const body = fence ? fence[1] : text;
  const start = body.indexOf("{");
  const end = body.lastIndexOf("}");
  if (start === -1 || end === -1 || end <= start) return body.trim();
  return body.slice(start, end + 1);
}

async function parseProposalWithRepair(raw: string, repair: (issues: string[], previous: unknown) => Promise<string>): Promise<{ ok: boolean; proposal?: CreativeProposal; issues: string[]; repaired: boolean }> {
  const attempt = (text: string): { ok: boolean; proposal?: CreativeProposal; issues: string[] } => {
    let json: unknown;
    try {
      json = JSON.parse(stripFences(text));
    } catch {
      return { ok: false, issues: ["Model output was not valid JSON"] };
    }
    const parsed = creativeProposalSchema.safeParse(json);
    if (!parsed.success) {
      return { ok: false, issues: parsed.error.issues.slice(0, 8).map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`) };
    }
    return { ok: true, proposal: parsed.data, issues: [] };
  };
  const first = attempt(raw);
  if (first.ok) return { ...first, repaired: false };
  const second = attempt(await repair(first.issues, safeJson(raw)));
  if (second.ok) return { ...second, repaired: true };
  return { ok: false, issues: second.issues, repaired: true };
}

function safeJson(raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

