export interface CreativePayload {
  version: 1;
  direction: "CODE_GIFTZ_TO_LAXII";
  request: string;
  repoId: string;
  proposal?: CreativeProposal;
  brief?: DesignBrief;
  digestSummary?: { fileCount: number; packageName: string | null };
  assetSpec: { kind: "BANNER"; width: number; height: number };
  artifactId?: string;
  mediaId?: string;
  result?: {
    width: number;
    height: number;
    mime: string;
    sizeBytes: number;
    provider: string;
    model: string;
    attempts: number;
    qualitySummary: string;
  };
  integrationTaskId?: string;
}

function parseSteps(raw: string | null): { step: string; status: string; note?: string; at?: string }[] {
  try {
    const arr = JSON.parse(raw ?? "[]");
    return Array.isArray(arr) ? arr : [];
  } catch {
    return [];
  }
}

function upsertStep(steps: { step: string; status: string; note?: string; at?: string }[], step: string, status: string, note?: string) {
  const next = steps.filter((s) => s.step !== step);
  next.push({ step, status, note, at: new Date().toISOString() });
  return next;
}

async function loadCreativeTask(userId: string, taskId: string) {
  const row = await db.agentTask.findFirst({ where: { id: taskId, userId, kind: CREATIVE_KIND } });
  if (!row) throw new CreativeTaskError("Creative asset task not found", 404);
  return row;
}

function payloadOf(row: { resultJson: string | null }): CreativePayload | null {
  try {
    const parsed = JSON.parse(row.resultJson ?? "null") as CreativePayload | null;
    return parsed && parsed.version === 1 ? parsed : null;
  } catch {
    return null;
  }
}

export interface CreativeTaskDetail {
  id: string;
  status: string;
  request: string;
  repoId: string | null;
  proposal: CreativeProposal | null;
  brief: DesignBrief | null;
  assetSpec: CreativePayload["assetSpec"];
  artifactId: string | null;
  mediaId: string | null;
  result: CreativePayload["result"] | null;
  integrationTaskId: string | null;
  digestSummary: CreativePayload["digestSummary"] | null;
  steps: { step: string; status: string; note?: string; at?: string }[];
  error: string | null;
  createdAt: string;
  updatedAt: string;
}

export async function loadCreativeTaskDetail(userId: string, taskId: string): Promise<CreativeTaskDetail> {
  const row = await loadCreativeTask(userId, taskId);
  const payload = payloadOf(row);
  return {
    id: row.id,
    status: row.status,
    request: payload?.request ?? row.title,
    repoId: row.repoId,
    proposal: payload?.proposal ?? null,
    brief: payload?.brief ?? null,
    assetSpec: payload?.assetSpec ?? { kind: "BANNER", width: 2048, height: 687 },
    artifactId: payload?.artifactId ?? null,
    mediaId: payload?.mediaId ?? null,
    result: payload?.result ?? null,
    integrationTaskId: payload?.integrationTaskId ?? null,
    digestSummary: payload?.digestSummary ?? null,
    steps: parseSteps(row.stepsJson),
    error: row.error,
    createdAt: row.createdAt.toISOString(),
    updatedAt: row.updatedAt.toISOString(),
  };
}

export async function listCreativeTasks(userId: string, limit = 20): Promise<CreativeTaskDetail[]> {
  const rows = await db.agentTask.findMany({
    where: { userId, kind: CREATIVE_KIND },
    orderBy: { updatedAt: "desc" },
    take: limit,
  });
  const out: CreativeTaskDetail[] = [];
  for (const row of rows) out.push(await loadCreativeTaskDetail(userId, row.id));
  return out;
}

