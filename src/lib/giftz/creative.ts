export async function createCreativeAssetTask(input: {
  userId: string;
  repoId: string;
  request: string;
  provider?: CreativeProposalProvider;
}): Promise<{ taskId: string; status: string; duplicate?: boolean }> {
  const request = input.request?.trim();
  if (!request || request.length < 8 || request.length > 2000) {
    throw new CreativeTaskError("Describe the creative asset request in 8–2000 characters");
  }
  const repo = await db.giftzRepository.findFirst({ where: { id: input.repoId, ownerId: input.userId, status: "READY" } });
  if (!repo) throw new CreativeTaskError("Repository not found", 404);

  const active = await db.agentTask.findFirst({
    where: { userId: input.userId, repoId: input.repoId, kind: CREATIVE_KIND, status: { in: ACTIVE_STATUSES } },
    orderBy: { createdAt: "desc" },
  });
  if (active) return { taskId: active.id, status: active.status, duplicate: true };

  const row = await db.agentTask.create({
    data: {
      userId: input.userId,
      agent: "CODE_GIFTZ",
      kind: CREATIVE_KIND,
      title: request.slice(0, 80),
      status: "QUEUED",
      repoId: input.repoId,
      stepsJson: JSON.stringify([{ step: "inspect", status: "pending" }]),
      resultJson: JSON.stringify({
        version: 1,
        direction: "CODE_GIFTZ_TO_LAXII",
        request,
        repoId: input.repoId,
        assetSpec: { kind: "BANNER", width: 2048, height: 687 },
      } satisfies CreativePayload),
    },
  });

  void runProposalPhase(row.id, input.userId, input.repoId, request, input.provider ?? createGatewayCreativeProvider(input.userId)).catch(async (error) => {
    const fresh = await db.agentTask.findUnique({ where: { id: row.id }, select: { stepsJson: true } });
    await db.agentTask
      .update({
        where: { id: row.id },
        data: {
          status: "FAILED",
          stepsJson: JSON.stringify(upsertStep(parseSteps(fresh?.stepsJson ?? "[]"), "propose", "failed", error instanceof Error ? error.message : "proposal failed")),
          error: (error instanceof Error ? error.message : "proposal failed").slice(0, 300),
        },
      })
      .catch(() => undefined);
  });

  return { taskId: row.id, status: "QUEUED" };
}

async function runProposalPhase(taskId: string, userId: string, repoId: string, request: string, provider: CreativeProposalProvider): Promise<void> {
  const write = async (status: string, steps: { step: string; status: string; note?: string; at?: string }[], payload: CreativePayload, error?: string) => {
    await db.agentTask.update({
      where: { id: taskId },
      data: { status, stepsJson: JSON.stringify(steps), resultJson: JSON.stringify(payload), ...(error ? { error: error.slice(0, 300) } : {}) },
    });
  };

  let steps = upsertStep([], "inspect", "running");
  let payload = payloadOf((await db.agentTask.findUnique({ where: { id: taskId }, select: { resultJson: true } }))!)!;
  await write("ANALYZING", steps, payload);
  const digest = inspectRepository(repoId);
  payload.digestSummary = { fileCount: digest.fileCount, packageName: digest.packageName };
  steps = upsertStep(steps, "inspect", "done", `${digest.fileCount} files`);
  await write("ANALYZING", steps, payload);

  steps = upsertStep(steps, "propose", "running");
  await write("PROPOSING", steps, payload);
  const raw = await provider.propose({ request, digest });
  const outcome = await parseProposalWithRepair(raw, async (issues, previous) => provider.propose({ request, digest, repairIssues: issues, previousProposal: previous }));
  if (!outcome.ok || !outcome.proposal) {
    steps = upsertStep(steps, "propose", "failed", "creative proposal failed validation");
    await write("FAILED", steps, payload, `The creative proposal did not pass validation: ${outcome.issues[0] ?? "unknown issue"}`);
    return;
  }
  payload.proposal = outcome.proposal;

  // The DesignBrief's authoritative parts (canvas 2048×687, safe area, palette
  // from the real site identity, portfolio context) come from the SAME builder
  // the RIISHE delegation uses — the proposal only steers headline/direction.
  const user = await db.user.findUnique({ where: { id: userId } });
  if (!user) throw new CreativeTaskError("User not found", 404);
  const seeded = await buildStructuredBannerBrief(
    user,
    `Design a new portfolio banner for my site with "${outcome.proposal.headline}" as the headline. Visual direction: ${outcome.proposal.visualDirection}`
  );
  const brief: DesignBrief = parseDesignBrief({
    ...seeded.brief,
    direction: outcome.proposal.visualDirection,
    targetAudience: outcome.proposal.audience ?? seeded.brief.targetAudience,
    avoid: [...new Set([...outcome.proposal.avoid, ...seeded.brief.avoid])].slice(0, 6),
  });

  payload.brief = brief;
  steps = upsertStep(steps, "propose", "done", "validated");
  await write("AWAITING_APPROVAL", steps, payload);
  void recordAiUsage(userId, "giftz-creative-brief");
}

